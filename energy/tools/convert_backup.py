def parse_sleep(s):
    """'1:40-7:30' → (시간, 취침, 기상) / '7.5' → (7.5, None, None)"""
    if not s:
        return None, None, None
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*-\s*(\d{1,2}):(\d{2})\s*$", s)
    if m:
        a = int(m[1]) * 60 + int(m[2])
        b = int(m[3]) * 60 + int(m[4])
        dur = b - a if b >= a else b + 1440 - a
        return round(dur / 60, 2), f"{m[1].zfill(2)}:{m[2]}", f"{m[3].zfill(2)}:{m[4]}"
    try:
        return float(s), None, None
    except ValueError:
        return None, None, None


